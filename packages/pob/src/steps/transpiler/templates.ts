/** rollup.config.mjs templates of pob:common:transpiler */

const escapeHtml = (value: string): string =>
  value.replaceAll(/[&<>"']/g, (character) => {
    switch (character) {
      case "&":
        return "&amp;";
      case "<":
        return "&lt;";
      case ">":
        return "&gt;";
      case '"':
        return "&#34;";
      default:
        return "&#39;";
    }
  });

const header = (rollupConfigLib: string): string =>
  `// Generated by pob: do not edit, it is overwritten on each pob run.
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import createRollupConfig from '@pob/${escapeHtml(rollupConfigLib)}/createRollupConfig.js';
`;

interface LibRollupConfigOptions {
  rollupConfigLib: string;
  outDirectory: string;
}

/** lib.rollup.config.mjs.ejs */
export const libRollupConfig = ({
  rollupConfigLib,
  outDirectory,
}: LibRollupConfigOptions): string =>
  `${header(rollupConfigLib)}
export default createRollupConfig({
  cwd: dirname(fileURLToPath(import.meta.url)),
  outDirectory: '${escapeHtml(outDirectory)}',
});
`;

interface AppRollupConfigOptions extends LibRollupConfigOptions {
  /** alp-rollup-plugin-config */
  config: boolean;
  /** run the built app in watch mode */
  enableRun: boolean;
}

const appConfigImport = "import config from 'alp-rollup-plugin-config';\n";

const appImports = ({
  rollupConfigLib,
  config,
  enableRun,
}: AppRollupConfigOptions): string => {
  if (enableRun) {
    return `import run from '@pob/${escapeHtml(rollupConfigLib)}/plugin-run.cjs';
${config ? appConfigImport : ""}
const watch = process.env.ROLLUP_WATCH === 'true';
`;
  }
  return config ? appConfigImport : "";
};

/** app.rollup.config.mjs.ejs */
export const appRollupConfig = (options: AppRollupConfigOptions): string =>
  `${header(options.rollupConfigLib)}${appImports(options)}
export default createRollupConfig({
  cwd: dirname(fileURLToPath(import.meta.url)),
  outDirectory: '${escapeHtml(options.outDirectory)}',
  plugins: [
${
  options.config
    ? `    config({
      targets: [{ src: 'src/config/**/*.yml' }],
    }),
`
    : ""
}${
    options.enableRun
      ? "    watch && run({ execArgv: ['--enable-source-maps'] }),\n"
      : ""
  }  ],
});
`;
