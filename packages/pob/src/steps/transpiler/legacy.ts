import type { JsonObject } from "../../engine/model.ts";
import type { LegacyPart } from "../legacy/part.ts";
import {
  getTranspilerOptions,
  resolveTranspilerBuild,
  usesTranspiler,
} from "./settings.ts";

/**
 * Root files of the entries, generated before package.json#exports. Only
 * these names can be declared: `files:*.js` would cover eslint.config.js.
 */
const declaredRootEntryFiles = ["index.js", "browser.js"];

/** from pob:common:babel */
export const babelLegacyPart: LegacyPart = {
  name: "babel",
  writes: [
    "pkg.dependencies",
    "pkg.devDependencies",
    "files:types.js",
    "files:rollup.config.js",
    "files:.babelrc",
    "files:babel.config.json",
    "files:babel.config.mjs",
    "files:babel.config.js",
    ...declaredRootEntryFiles.map((file) => `files:${file}`),
  ],
  run: (ctx) => {
    if (!usesTranspiler(ctx)) return;
    const { pkg, output } = ctx;
    const initialPkg = ctx.initial.readJson<JsonObject>("package.json") ?? {};
    const devDependencies = initialPkg.devDependencies as
      | JsonObject
      | undefined;
    const name = (initialPkg.name ?? "") as string;

    const { build, useBabel } = resolveTranspilerBuild(
      ctx,
      getTranspilerOptions(ctx),
    );
    if (useBabel) return;
    for (const entry of (build.entries ?? []) as unknown[]) {
      if (typeof entry !== "string") continue;
      const file = `${entry}.js`;
      if (declaredRootEntryFiles.includes(file)) {
        output.removed(file);
      } else if (ctx.initial.exists(file)) {
        ctx.warn(`${file}: generated by an old pob version, delete it`);
      }
    }

    if (devDependencies?.["pob-babel"]) {
      pkg.removeDevDependencies(["pob-babel", "@babel/core"]);
      pkg.removeDependencies(["@babel/runtime"]);
    }
    pkg.removeDevDependencies([
      "babel-preset-env",
      "babel-preset-jsdoc",
      "babel-plugin-add-jsdoc-annotations",
      "babel-preset-modern-browsers",
      "@rollup/plugin-run",
    ]);
    // rollup plugins may use @babel/preset-env themselves
    if (
      !(
        name.includes("rollup-plugin") && devDependencies?.["@babel/preset-env"]
      )
    ) {
      pkg.removeDevDependencies(["@babel/preset-env"]);
    }

    output.removed("types.js");
    output.removed("rollup.config.js");
    output.removed(".babelrc");
    output.removed("babel.config.json");
    output.removed("babel.config.mjs");
    output.removed("babel.config.js");
  },
};

const legacyBuildKeys = ["browser-dev", "module-dev"];

/** from pob:common:transpiler */
export const transpilerLegacyPart: LegacyPart = {
  name: "transpiler",
  // `module:*` and `webpack:*` keys: any top-level key
  writes: ["pkg.*"],
  run: (ctx) => {
    if (!usesTranspiler(ctx)) return;
    const { pkg } = ctx;
    pkg.removeScripts(["postbuild", "build:dev", "watch:dev"]);
    const keys = Object.keys(
      ctx.initial.readJson<JsonObject>("package.json") ?? {},
    );
    for (const key of keys) {
      if (
        legacyBuildKeys.includes(key) ||
        key.startsWith("module:") ||
        key.startsWith("webpack:")
      ) {
        pkg.delete(key);
      }
    }
  },
};
