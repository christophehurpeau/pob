import type { PackageContext } from "../engine/context.ts";
import { defineStep } from "../engine/step.ts";
import {
  getAppIgnorePaths,
  getAppSettings,
  getLibSettings,
  getMonorepoSettings,
  getProjectKind,
} from "./settings.ts";

export interface GitignoreOptions {
  root: boolean;
  documentation: boolean;
  testing: boolean;
  withBabel: boolean | undefined;
  typescript: boolean;
  paths: string;
  playwright: boolean;
  designSync: boolean;
}

const rootSection = (
  options: GitignoreOptions,
  typescript: boolean,
): string[] => [
  "",
  "# IDE",
  "/.settings",
  "/.project",
  "/.idea",
  "!/.vscode",
  "*.sublime-project",
  "*.sublime-workspace",
  ...(options.documentation || options.testing
    ? ["", "# generated documentation and coverage output", "/generated-docs"]
    : []),
  ...(options.testing ? ["", "# default coverage directory", "/coverage"] : []),
  ...(typescript ? ["", "# Typescript", "*.tsbuildinfo"] : []),
  ...(options.playwright
    ? ["", "# Playwright", "/test-results", "/playwright-report"]
    : []),
  ...(options.designSync
    ? ["", "# Claude Design sync", "/.ds-sync/", "/ds-bundle/"]
    : []),
  "",
  "#*",
  "*$",
  "*.BAK",
  "*.bak",
  "*.log",
  "*.old",
  "*~",
  ".#*",
  ".DS_Store",
];

export const renderGitignore = (options: GitignoreOptions): string => {
  const typescript = !!options.withBabel || options.typescript;
  const lines = [
    "# Generated by pob: do not edit, it is overwritten on each pob run.",
    ...(options.root
      ? [
          "# dependencies",
          "node_modules",
          "/.pnp",
          ".pnp.js",
          "npm-debug.log*",
          "yarn-debug.log*",
          "yarn-error.log*",
        ]
      : []),
    ...(options.paths ? [...(options.root ? [""] : []), options.paths] : []),
    ...(options.root ? rootSection(options, typescript) : []),
  ];
  return `${lines.join("\n")}\n`;
};

const getGitignoreOptions = (ctx: PackageContext): GitignoreOptions => {
  const designSync = ctx.initial.exists(".design-sync/config.json");
  switch (getProjectKind(ctx)) {
    case "monorepo": {
      const settings = getMonorepoSettings(ctx);
      return {
        root: true,
        documentation: !!settings.monorepo.documentation,
        testing: !!settings.monorepo.testing,
        withBabel: undefined,
        typescript: !!settings.monorepo.typescript,
        paths: settings.rootIgnorePaths.join("\n"),
        playwright: false,
        designSync,
      };
    }
    case "app": {
      const settings = getAppSettings(ctx.config);
      const ignorePaths = getAppIgnorePaths(
        settings.app,
        ctx.initial.readJson("package.json"),
      );
      if (ctx.initial.exists(".env.example")) {
        ignorePaths.push("/.env*", "!/.env.example");
      }
      return {
        root: !ctx.facts.inMonorepo,
        documentation: false,
        testing: !!settings.app.testing,
        withBabel: settings.babel,
        typescript: true,
        paths: ignorePaths.join("\n"),
        playwright: false,
        designSync,
      };
    }
    case "lib": {
      const settings = getLibSettings(ctx.config);
      return {
        root: !ctx.facts.inMonorepo,
        documentation: settings.documentation,
        testing: settings.testing,
        withBabel: settings.withBabel,
        typescript: settings.withTypescript,
        paths:
          !settings.buildInGit && settings.buildDirectory
            ? `/${settings.buildDirectory}`
            : "",
        playwright: settings.e2e,
        designSync,
      };
    }
    default:
      throw new Error("Unknown project kind");
  }
};

/** .gitignore, owned. npm publish also reads it. */
export const gitignoreStep = defineStep<PackageContext>({
  name: "gitignore",
  writes: ["files:.gitignore", "files:.cursorignore"],
  run: (ctx) => {
    const options = getGitignoreOptions(ctx);
    if (
      !options.root &&
      !options.documentation &&
      !options.paths &&
      !options.withBabel
    ) {
      ctx.output.removed(".gitignore");
    } else {
      ctx.output.owned(".gitignore", renderGitignore(options));
    }
    ctx.output.removed(".cursorignore");
  },
});
