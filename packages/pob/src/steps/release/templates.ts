const unsupported = (packageManager: never): never => {
  throw new Error(`Unsupported package manager: ${String(packageManager)}`);
};

const githubExpression = (expression: string): string =>
  `\${{ ${expression} }}`;

export interface ReleaseWorkflowOptions {
  packageManager: PackageManager;
  enablePublish: boolean;
  build: boolean;
  disableYarnGitCache: boolean;
  isMonorepo: boolean;
  isMonorepoIndependent: boolean;
}

const setupPackageManagerLines = (packageManager: PackageManager): string[] => {
  switch (packageManager) {
    case "yarn":
      return [
        "",
        "      - name: Enable Corepack",
        "        run: corepack enable",
      ];
    case "bun":
      return [
        "",
        "      - name: Install bun",
        "        uses: oven-sh/setup-bun@v2",
        "        with:",
        "          bun-version: latest",
      ];
    case "pnpm":
      return [
        "",
        "      - name: Install pnpm",
        "        uses: pnpm/action-setup@v6",
      ];
    case "npm":
      return [];
    default:
      return unsupported(packageManager);
  }
};

const installLines = (
  packageManager: PackageManager,
  disableYarnGitCache: boolean,
): string[] => {
  switch (packageManager) {
    case "yarn":
      return [
        "",
        "      - name: Install Dependencies",
        disableYarnGitCache
          ? "        run: yarn install --immutable"
          : "        run: yarn install --immutable --immutable-cache",
      ];
    case "bun":
      return [
        "      - name: Install Dependencies",
        "        run: bun install --frozen-lockfile",
      ];
    case "pnpm":
      return [
        "      - name: Install Dependencies",
        "        run: pnpm install --frozen-lockfile",
      ];
    case "npm":
      return [];
    default:
      return unsupported(packageManager);
  }
};

const publishLines = (
  packageManager: PackageManager,
  isMonorepo: boolean,
): string[] => {
  const command = (() => {
    switch (packageManager) {
      case "yarn":
        return isMonorepo
          ? "yarn workspaces foreach --all --parallel --no-private npm publish --tolerate-republish --provenance"
          : "yarn npm publish --provenance";
      case "pnpm":
        return isMonorepo
          ? "pnpm -r publish --no-git-checks --provenance"
          : "pnpm publish --no-git-checks --provenance";
      case "bun":
      case "npm":
        return undefined;
      default:
        return unsupported(packageManager);
    }
  })();
  if (command === undefined) return [];
  return [
    "",
    "      - name: Publish to npm",
    "        if: github.ref == 'refs/heads/main' && !inputs.dry-run",
    "        run: |",
    `          ${command}`,
  ];
};

/** lib/generators/common/release/templates/workflow-release.yml.ejs */
export const releaseWorkflowTemplate = ({
  packageManager,
  enablePublish,
  build,
  disableYarnGitCache,
  isMonorepo,
  isMonorepoIndependent,
}: ReleaseWorkflowOptions): string => {
  const independent = isMonorepo && isMonorepoIndependent;
  const pobVersion = packageManagerExec(packageManager, "pob-version");
  const bumpDependents = independent
    ? ` --bump-dependents-highest-as=${githubExpression("inputs.bump-dependents-highest-as")}`
    : "";
  const force = githubExpression(
    "inputs.force != 'none' && format('--force={0}', inputs.force) || ''",
  );
  const publishFlags =
    enablePublish && packageManager === "bun"
      ? "--publish --publish-provenance "
      : "";
  const message = `'chore: release ${isMonorepoIndependent ? "" : "%v "}[skip ci]${isMonorepoIndependent ? String.raw`\n\n%t` : ""}'`;

  const lines = [
    "# Generated by pob: do not edit, it is overwritten on each pob run.",
    "name: Release",
    "on:",
    "  workflow_dispatch:",
    "    inputs:",
    "      dry-run:",
    '        description: "Dry run"',
    "        required: true",
    "        type: boolean",
    "        default: false",
    "      allow-no-tags:",
    '        description: "Allow no tags"',
    "        required: false",
    "        type: boolean",
    "        default: false",
    ...(independent
      ? [
          "      bump-dependents-highest-as:",
          '        description: "Bump dependents highest version as"',
          "        required: true",
          "        type: choice",
          "        options:",
          "          - major",
          "          - minor",
          "          - patch",
          "        default: major",
        ]
      : []),
    "      force:",
    '        description: "Force bump all packages, even without changes"',
    "        required: true",
    "        type: choice",
    "        options:",
    "          - none",
    "          - major",
    "          - minor",
    "          - patch",
    "        default: none",
    "",
    "permissions:",
    "  id-token: write # Required for OIDC",
    "  contents: write",
    "",
    "jobs:",
    "  release:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - uses: actions/checkout@v7",
    "        with:",
    `          ssh-key: ${githubExpression("secrets.PUSH_DEPLOY_KEY")}`,
    "          fetch-depth: 0",
    "          fetch-tags: true",
    ...setupPackageManagerLines(packageManager),
    "",
    "      - uses: actions/setup-node@v7",
    "        with:",
    `          node-version: ${latestLTS}`,
    '          registry-url: "https://registry.npmjs.org"',
    "",
    "      - name: Check git tags",
    "        if: github.ref == 'refs/heads/main' && !inputs.allow-no-tags",
    "        run: |",
    "          tags=$(git tag)",
    '          if [ -z "$tags" ]; then',
    '            echo "No git tags found"',
    "            exit 1",
    "          fi",
    ...installLines(packageManager, disableYarnGitCache),
    ...(build
      ? [
          "",
          "      - name: Build",
          `        run: ${packageManagerRun(packageManager, "build")}`,
        ]
      : []),
    "",
    "      - name: New version (dry run)",
    "        if: github.ref == 'refs/heads/main' && inputs.dry-run",
    `        run: ${pobVersion} --dry-run${bumpDependents} ${force}`,
    "",
    "      - name: Configure Git user",
    "        if: github.ref == 'refs/heads/main' && !inputs.dry-run",
    "        run: |",
    "          git config --global user.name 'github-actions[bot]'",
    "          git config --global user.email 'github-actions[bot]@users.noreply.github.com'",
    "",
    "      - name: New version",
    "        if: github.ref == 'refs/heads/main' && !inputs.dry-run",
    "        run: |",
    `          ${pobVersion} ${publishFlags}--create-release=github${bumpDependents} ${force} -m ${message}`,
    "        env:",
    "          POB_GIT_HOOKS: 0",
    "          YARN_ENABLE_IMMUTABLE_INSTALLS: false",
    `          GH_TOKEN: ${githubExpression("secrets.GITHUB_TOKEN")}`,
    ...(enablePublish ? publishLines(packageManager, isMonorepo) : []),
  ];
  return `${lines.join("\n")}\n`;
};
