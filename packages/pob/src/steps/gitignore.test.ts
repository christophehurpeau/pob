import { describe, expect, test } from "vitest";
import {
  createTestContext,
  plannedContent,
  runTestSteps,
} from "../engine/testing.ts";
import { gitignoreStep } from "./gitignore.ts";

const yoRc = (pob: unknown): string => JSON.stringify({ pob });

describe("gitignore", () => {
  test("typescript lib with testing", async () => {
    const plan = await runTestSteps(
      createTestContext({
        files: {
          "package.json": JSON.stringify({
            name: "lib",
            pob: { bundler: "rollup-esbuild", typescript: true },
          }),
          ".yo-rc.json": yoRc({
            project: { type: "lib", packageManager: "pnpm", ci: true },
            lib: { testing: { runner: "vitest" }, e2e: true },
          }),
          ".cursorignore": "",
        },
      }),
      [gitignoreStep],
    );
    expect(plannedContent(plan, ".gitignore"))
      .toBe(`# Generated by pob: do not edit, it is overwritten on each pob run.
# dependencies
node_modules
/.pnp
.pnp.js
npm-debug.log*
yarn-debug.log*
yarn-error.log*

/dist

# IDE
/.settings
/.project
/.idea
!/.vscode
*.sublime-project
*.sublime-workspace

# generated documentation and coverage output
/generated-docs

# default coverage directory
/coverage

# Typescript
*.tsbuildinfo

# Playwright
/test-results
/playwright-report

#*
*$
*.BAK
*.bak
*.log
*.old
*~
.#*
.DS_Store
`);
    expect(plan.files.find((file) => file.path === ".cursorignore")?.op).toBe(
      "delete",
    );
  });

  test("monorepo package without anything to ignore has no .gitignore", async () => {
    const plan = await runTestSteps(
      createTestContext({
        files: {
          "package.json": JSON.stringify({ name: "a", pob: {} }),
          ".yo-rc.json": yoRc({ project: { type: "lib" }, lib: {} }),
          ".gitignore": "old",
        },
        facts: {
          isRoot: false,
          inMonorepo: {
            rootDir: "/test",
            relative: "packages/a",
            rootPkg: {},
            rootConfig: { project: { type: "lib", packageManager: "yarn" } },
          },
        },
      }),
      [gitignoreStep],
    );
    expect(
      plan.files
        .filter(({ path }) => path !== "package.json")
        .map(({ path, op }) => `${op} ${path}`),
    ).toEqual(["delete .gitignore"]);
  });

  test("app ignores its env files except the example", async () => {
    const plan = await runTestSteps(
      createTestContext({
        files: {
          "package.json": JSON.stringify({ name: "app" }),
          ".yo-rc.json": yoRc({
            project: { type: "app", packageManager: "yarn", ci: true },
            app: { type: "vite" },
          }),
          ".env.example": "",
        },
      }),
      [gitignoreStep],
    );
    expect(plannedContent(plan, ".gitignore")).toContain(
      "yarn-error.log*\n\n/dist\n/.env*\n!/.env.example\n\n# IDE",
    );
  });
});
