import { describe, expect, test } from "vitest";
import {
  createTestContext,
  plannedContent,
  runTestSteps,
} from "../engine/testing.ts";
import { gitignoreStep } from "./gitignore.ts";

const yoRc = (pob: unknown): string => JSON.stringify({ pob });

describe("gitignore", () => {
  test("typescript lib with testing", async () => {
    const plan = await runTestSteps(
      createTestContext({
        files: {
          "package.json": JSON.stringify({
            name: "lib",
            pob: { bundler: "rollup-esbuild", typescript: true },
          }),
          ".yo-rc.json": yoRc({
            project: { type: "lib", packageManager: "pnpm", ci: true },
            lib: { testing: { runner: "vitest" }, e2e: true },
          }),
          ".cursorignore": "",
        },
      }),
      [gitignoreStep],
    );
    expect(plannedContent(plan, ".gitignore"))
      .toBe(`# Generated by pob: do not edit, it is overwritten on each pob run.
# dependencies
node_modules
/.pnp
.pnp.js
npm-debug.log*
yarn-debug.log*
yarn-error.log*

/dist

# IDE
/.settings
/.project
/.idea
!/.vscode
*.sublime-project
*.sublime-workspace

# generated documentation and coverage output
/generated-docs

# default coverage directory
/coverage

# Typescript
*.tsbuildinfo

# Playwright
/test-results
/playwright-report

#*
*$
*.BAK
*.bak
*.log
*.old
*~
.#*
.DS_Store
`);
    expect(plan.files.find((file) => file.path === ".cursorignore")?.op).toBe(
      "delete",
    );
  });

  test("monorepo package without anything to ignore has no .gitignore", async () => {
    const plan = await runTestSteps(
      createTestContext({
        files: {
          "package.json": JSON.stringify({ name: "a", pob: {} }),
          ".yo-rc.json": yoRc({ project: { type: "lib" }, lib: {} }),
          ".gitignore": "old",
        },
        facts: {
          isRoot: false,
          inMonorepo: {
            rootDir: "/test",
            relative: "packages/a",
            rootPkg: {},
            rootConfig: { project: { type: "lib", packageManager: "yarn" } },
          },
        },
      }),
      [gitignoreStep],
    );
    expect(
      plan.files
        .filter(({ path }) => path !== "package.json")
        .map(({ path, op }) => `${op} ${path}`),
    ).toEqual(["delete .gitignore"]);
  });

  const libPackage = (pobJson: unknown) =>
    createTestContext({
      files: {
        "package.json": JSON.stringify({
          name: "a",
          devDependencies: { "@storybook/react-vite": "1.0.0" },
        }),
        "pob.json": JSON.stringify(pobJson),
      },
      facts: {
        isRoot: false,
        inMonorepo: {
          rootDir: "/test",
          relative: "packages/a",
          rootPkg: {},
          rootConfig: { project: { type: "lib", packageManager: "yarn" } },
        },
      },
    });

  test("monorepo lib with storybook and paths from the config keeps a .gitignore", async () => {
    const plan = await runTestSteps(
      libPackage({
        project: { type: "lib" },
        lib: {},
        gitignore: ["/snapshots/"],
      }),
      [gitignoreStep],
    );
    expect(plannedContent(plan, ".gitignore")).toBe(
      "# Generated by pob: do not edit, it is overwritten on each pob run.\n/storybook-static/\n/snapshots/\n",
    );
  });

  test("gitignore of the config must be an array of paths", async () => {
    await expect(
      runTestSteps(
        libPackage({
          project: { type: "lib" },
          lib: {},
          gitignore: "/snapshots/",
        }),
        [gitignoreStep],
      ),
    ).rejects.toThrow("pob.json: gitignore must be an array of paths");
  });

  test("root lib appends the paths of the config to its own", async () => {
    const plan = await runTestSteps(
      createTestContext({
        files: {
          "package.json": JSON.stringify({ name: "lib" }),
          "pob.json": JSON.stringify({
            project: { type: "lib", packageManager: "yarn", ci: true },
            lib: {},
            build: { bundler: "rollup-esbuild", typescript: true },
            gitignore: ["/snapshots/"],
          }),
        },
      }),
      [gitignoreStep],
    );
    expect(plannedContent(plan, ".gitignore")).toContain(
      "yarn-error.log*\n\n/dist\n/snapshots/\n\n# IDE",
    );
  });

  test("app ignores its env files except the example", async () => {
    const plan = await runTestSteps(
      createTestContext({
        files: {
          "package.json": JSON.stringify({ name: "app" }),
          ".yo-rc.json": yoRc({
            project: { type: "app", packageManager: "yarn", ci: true },
            app: { type: "vite" },
          }),
          ".env.example": "",
        },
      }),
      [gitignoreStep],
    );
    expect(plannedContent(plan, ".gitignore")).toContain(
      "yarn-error.log*\n\n/dist\n/.env*\n!/.env.example\n\n# IDE",
    );
  });

  test("monorepo expo package with storybook and paths from the config", async () => {
    const plan = await runTestSteps(
      createTestContext({
        files: {
          "package.json": JSON.stringify({
            name: "app",
            devDependencies: { "@storybook/react-vite": "1.0.0" },
          }),
          "pob.json": JSON.stringify({
            project: { type: "app" },
            app: { type: "expo" },
            gitignore: ["/snapshots/"],
          }),
        },
        facts: {
          isRoot: false,
          inMonorepo: {
            rootDir: "/test",
            relative: "packages/app",
            rootPkg: {},
            rootConfig: { project: { type: "lib", packageManager: "pnpm" } },
          },
        },
      }),
      [gitignoreStep],
    );
    expect(plannedContent(plan, ".gitignore"))
      .toBe(`# Generated by pob: do not edit, it is overwritten on each pob run.
/.expo/
/android/
/ios/
/dist/
/dist-native/
/web-build/
/.expo-shared/
*.jks
*.p8
*.p12
*.key
*.mobileprovision
*.orig.*
*.icon/
/storybook-static/
/snapshots/
`);
  });
});
