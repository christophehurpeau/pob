import { spawnSync } from "node:child_process";
import { lt } from "semver";
import type { PackageContext } from "../../engine/context.ts";
import type { JsonObject } from "../../engine/model.ts";
import { defineStep } from "../../engine/step.ts";
import { minimumReleaseAgeExcludePatterns } from "../../utils/misc.ts";
import { parseYamlConfig, runCommand, serializeYamlConfig } from "./shared.ts";

export const yarnVersion = "4.15.0";

export const parseYarnrc = parseYamlConfig({ json: true });

export const yarnGitignoreTemplate = ({
  disableYarnGitCache,
}: {
  disableYarnGitCache: boolean;
}): string => `# Generated by pob: do not edit, it is overwritten on each pob run.
/unplugged
/install-state.gz
${disableYarnGitCache ? "/cache\n" : ""}`;

export const isYarnEnabled = (ctx: PackageContext): boolean =>
  ctx.facts.isRoot && ctx.facts.packageManager === "yarn";

const postinstallDevPluginName = "@yarnpkg/plugin-postinstall-dev";
const legacyVersionPluginName = "@yarnpkg/plugin-conventional-version";

const pluginPath = (entry: unknown): string => {
  if (typeof entry === "string") return entry;
  const entryPath = (entry as JsonObject | null)?.path;
  return typeof entryPath === "string" ? entryPath : "";
};

/**
 * The plugins of `.yarnrc.yml` pob removes: a first filter, so that the
 * effect, which asks yarn for the plugins really loaded, is only planned when
 * it can do something.
 */
const getDeclaredPluginsToRemove = (
  ctx: PackageContext,
  pkgName: string | undefined,
): string[] => {
  const content = ctx.initial.read(".yarnrc.yml");
  if (content === undefined) return [];
  const plugins = parseYarnrc(content).plugins;
  if (!Array.isArray(plugins)) return [];
  const candidates = [
    postinstallDevPluginName,
    pkgName !== "yarn-plugin-conventional-version" && legacyVersionPluginName,
  ].filter((name): name is string => !!name);
  return candidates.filter((name) =>
    plugins.some((entry) => pluginPath(entry).includes(name)),
  );
};

const getRuntimePluginNames = (cwd: string): string[] => {
  const { stdout } = spawnSync("yarn", ["plugin", "runtime", "--json"], {
    cwd,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  });
  return (stdout ?? "")
    .split("\n")
    .filter(Boolean)
    .map((line) => (JSON.parse(line) as { name: string }).name);
};

/**
 * The yeoman generator deleted the directory through mem-fs, whose glob skips
 * dotfiles: `.yarn/.gitignore` was kept.
 */
const removeYarnDirectory = (ctx: PackageContext): void => {
  for (const file of ctx.initial.listFiles(".yarn")) {
    const relative = file.slice(".yarn/".length).split("/");
    if (!relative.some((segment) => segment.startsWith("."))) {
      ctx.output.removed(file);
    }
  }
};

const planYarnEffects = (ctx: PackageContext): void => {
  if (!ctx.initial.exists(".yarnrc.yml")) {
    ctx.effects.add({
      id: "yarn-set-version",
      reason: "no .yarnrc.yml: yarn berry is not installed yet",
      command: "yarn set version stable",
      mayModify: ["package.json", ".yarnrc.yml", ".yarn/releases/**"],
      run: ({ cwd }) => {
        runCommand(cwd, "yarn", ["set", "version", "stable"]);
      },
    });
  }

  const pluginsToRemove = getDeclaredPluginsToRemove(
    ctx,
    ctx.pkg.get<string>("name"),
  );
  if (pluginsToRemove.length > 0) {
    ctx.effects.add({
      id: "yarn-plugins",
      reason: `obsolete yarn plugins: ${pluginsToRemove.join(", ")}`,
      command: pluginsToRemove
        .map((name) => `yarn plugin remove ${name}`)
        .join(" && "),
      mayModify: [".yarnrc.yml", ".yarn/plugins/**"],
      run: ({ cwd }) => {
        const installed = getRuntimePluginNames(cwd);
        for (const name of pluginsToRemove) {
          if (installed.includes(name)) {
            runCommand(cwd, "yarn", ["plugin", "remove", name]);
          }
        }
      },
    });
  }
};

const writeYarnrc = (ctx: PackageContext): void => {
  const { config, facts, output } = ctx;
  const disableYarnGitCache = config.project.disableYarnGitCache !== false;
  const yarnrc = ctx.model("yarnrc", ".yarnrc.yml", parseYarnrc);
  if (yarnrc.get("enableScripts") === "true") {
    yarnrc.set("enableScripts", true);
  }
  if (disableYarnGitCache) {
    yarnrc.delete("compressionLevel");
    yarnrc.set("enableGlobalCache", true);
    yarnrc.delete("supportedArchitectures");
  } else {
    // optimized for the github cache
    yarnrc.set("compressionLevel", 0);
    yarnrc.set("enableGlobalCache", false);
    // every supported architecture in the yarn cache
    yarnrc.set("supportedArchitectures", {
      cpu: ["x64", "arm64"],
      os: ["linux", "darwin"],
      libc: ["glibc", "musl"],
    });
  }
  yarnrc.set(
    "defaultSemverRangePrefix",
    config.project.type === "app" ? "" : "^",
  );
  yarnrc.delete("enableMessageNames");
  // without yarnNodeLinker, yarn uses its default linker: pnp
  if (facts.yarnNodeLinker) yarnrc.set("nodeLinker", facts.yarnNodeLinker);
  else yarnrc.delete("nodeLinker");
  yarnrc.set("npmMinimalAgeGate", 1440 * 2.5);
  yarnrc.set("npmPreapprovedPackages", [...minimumReleaseAgeExcludePatterns]);

  const yarnPath = yarnrc.get<string>("yarnPath");
  if (yarnPath) {
    output.removed(yarnPath);
    yarnrc.delete("yarnPath");
  }

  output.merged(".yarnrc.yml", yarnrc, serializeYamlConfig, {
    format: "oxfmt",
  });
};

const updatePinst = (ctx: PackageContext, enabled: boolean): void => {
  const { pkg, facts } = ctx;
  const isStandalone = !facts.isMonorepoRoot && !facts.inMonorepo;
  if (enabled && isStandalone && !pkg.get("private")) {
    pkg.addDevDependencies(["pinst"]);
    pkg.addScripts({
      prepack: "pinst --disable",
      postpack: "pinst --enable",
    });
    return;
  }
  pkg.removeDevDependencies(["pinst"]);
  if (pkg.get("scripts.prepack") === "pinst --disable") {
    pkg.delete("scripts.prepack");
  }
  if (pkg.get("scripts.postpack") === "pinst --enable") {
    pkg.delete("scripts.postpack");
  }
};

/** pob:core:yarn: .yarnrc.yml, packageManager, pinst */
export const yarnStep = defineStep<PackageContext>({
  name: "yarn",
  // pnpm removes a pnpm packageManager that yarn then replaces
  overrides: ["pnpm"],
  reads: ["pkg.name", "pkg.private"],
  writes: [
    "pkg.devDependencies.pinst",
    "pkg.scripts.prepack",
    "pkg.scripts.postpack",
    "pkg.packageManager",
    "yarnrc",
    "files:.yarn/**",
    "files:.yarnrc.yml",
    "files:yarn.lock",
    "files:package-lock.json",
  ],
  run(ctx) {
    const { pkg, output } = ctx;
    const enabled = isYarnEnabled(ctx);
    updatePinst(ctx, enabled);

    if (!enabled) {
      if (pkg.get<string>("packageManager")?.startsWith("yarn@")) {
        pkg.delete("packageManager");
      }
      removeYarnDirectory(ctx);
      output.removed(".yarnrc.yml");
      output.removed("yarn.lock");
      return;
    }

    const disableYarnGitCache =
      ctx.config.project.disableYarnGitCache !== false;
    output.owned(
      ".yarn/.gitignore",
      yarnGitignoreTemplate({ disableYarnGitCache }),
    );
    planYarnEffects(ctx);

    const packageManager = pkg.get<string>("packageManager");
    if (
      !packageManager?.startsWith("yarn@") ||
      lt(packageManager.slice("yarn@".length), yarnVersion)
    ) {
      pkg.set("packageManager", `yarn@${yarnVersion}`);
    }

    writeYarnrc(ctx);

    if (ctx.facts.yarnNodeLinker !== "pnp") output.removed(".yarn/sdks");
    if (disableYarnGitCache) output.removed(".yarn/cache");
    output.removed("package-lock.json");
  },
});
