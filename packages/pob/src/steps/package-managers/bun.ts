import type { PackageContext } from "../../engine/context.ts";
import { defineStep } from "../../engine/step.ts";
import { minimumReleaseAgeExcludeNames } from "../../utils/misc.ts";

export const bunfigTemplate = ({
  minimumReleaseAgeExcludes,
}: {
  minimumReleaseAgeExcludes: readonly string[];
}): string => `# Generated by pob: do not edit, it is overwritten on each pob run.
[install]
# Only install package versions published at least 2.5 days ago
minimumReleaseAge = 216000 # seconds
minimumReleaseAgeExcludes = [
${minimumReleaseAgeExcludes.map((name) => `  ${JSON.stringify(name)},\n`).join("")}]

[test]
# dist is build output: its compiled *.test.js copies would otherwise run too.
pathIgnorePatterns = ["**/dist/**"]
`;

export const isBunEnabled = (ctx: PackageContext): boolean =>
  ctx.facts.isRoot && ctx.facts.packageManager === "bun";

/** pob:core:bun: bunfig.toml */
export const bunStep = defineStep<PackageContext>({
  name: "bun",
  writes: ["files:bunfig.toml", "files:bun.lock"],
  run(ctx) {
    if (isBunEnabled(ctx)) {
      ctx.output.owned(
        "bunfig.toml",
        bunfigTemplate({
          minimumReleaseAgeExcludes: minimumReleaseAgeExcludeNames,
        }),
      );
    } else {
      ctx.output.removed("bun.lock");
      ctx.output.removed("bunfig.toml");
    }
  },
});
