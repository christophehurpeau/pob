import { describe, expect, test } from "vitest";
import type { PackageContext } from "../../engine/context.ts";
import {
  createTestContext,
  plannedContent,
  runTestSteps,
} from "../../engine/testing.ts";
import { legacyStep } from "../legacy/index.ts";
import { monorepoBuildStep } from "./build.ts";
import { monorepoSteps } from "./index.ts";
import { monorepoTypescriptStep } from "./typescript.ts";
import { monorepoWorkspacesStep } from "./workspaces.ts";

const json = (value: unknown): string => JSON.stringify(value, null, 2);

const createPackage = (
  location: string,
  {
    pkg,
    config,
    files = {},
  }: {
    pkg: Record<string, unknown>;
    config: Record<string, unknown>;
    files?: Record<string, string>;
  },
): PackageContext =>
  createTestContext({
    location,
    files: {
      "package.json": json(pkg),
      ".yo-rc.json": json({ pob: config }),
      ...files,
    },
    facts: { isRoot: false },
  });

const createRoot = ({
  pkg = {},
  monorepo = {},
  project = {},
  files = {},
  workspacePackages = [],
}: {
  pkg?: Record<string, unknown>;
  monorepo?: Record<string, unknown>;
  project?: Record<string, unknown>;
  files?: Record<string, string>;
  workspacePackages?: PackageContext[];
}): PackageContext =>
  createTestContext({
    files: {
      "package.json": json({
        name: "test-monorepo",
        private: true,
        workspaces: ["packages/*"],
        ...pkg,
      }),
      ".yo-rc.json": json({
        pob: {
          project: {
            type: "lib",
            packageManager: "yarn",
            ci: true,
            ...project,
          },
          monorepo: { eslint: true, ...monorepo },
        },
      }),
      ...files,
    },
    facts: { isMonorepoRoot: true, isRoot: true },
    workspacePackages,
  });

const plannedPkg = (
  plan: Awaited<ReturnType<typeof runTestSteps>>,
): Record<string, unknown> =>
  JSON.parse(plannedContent(plan, "package.json") ?? "{}") as Record<
    string,
    unknown
  >;

const libPackage = (
  location: string,
  name: string,
  extra: Record<string, unknown> = {},
  files: Record<string, string> = {},
): PackageContext =>
  createPackage(location, {
    pkg: {
      name,
      pob: { bundler: "rollup-esbuild", typescript: true },
      ...extra,
    },
    config: { project: { type: "lib" }, lib: {} },
    files: { "tsconfig.json": "{}", ...files },
  });

describe("monorepo steps", () => {
  test("do not run outside a monorepo root", async () => {
    const plan = await runTestSteps(
      createTestContext({
        files: {
          "package.json": json({ name: "lib" }),
          ".yo-rc.json": json({
            pob: { project: { type: "lib", packageManager: "yarn", ci: true } },
          }),
        },
      }),
      monorepoSteps,
    );
    expect(plan.files.filter((file) => file.path !== "package.json")).toEqual(
      [],
    );
  });

  test("rollup configs and typescript definitions chain the root build", async () => {
    const plan = await runTestSteps(
      createRoot({
        project: { packageManager: "pnpm" },
        monorepo: { typescript: true },
        workspacePackages: [
          libPackage(
            "packages/plugin",
            "plugin",
            {
              scripts: { build: "rollup" },
            },
            { "rollup.config.mjs": "export default [];\n" },
          ),
          libPackage(
            "packages/lib",
            "lib",
            {},
            {
              "rollup.config.mjs":
                'import plugin from "plugin";\nexport default [];\n',
            },
          ),
        ],
      }),
      [monorepoBuildStep, monorepoTypescriptStep],
    );
    const pkg = plannedPkg(plan);
    expect(pkg.scripts).toEqual({
      build:
        'pnpm --filter "plugin" run build && pnpm run clean:build && rollup --config rollup.config.mjs && pnpm run build:definitions',
      "build:definitions": "tsrs -b",
      "clean:build": 'pnpm -r --parallel --filter "!plugin" run clean:build',
      tsc: "tsrs -b",
      "tsc:go": "tsc -b",
      watch:
        'pnpm --filter "plugin" run build && pnpm run clean:build && rollup --config rollup.config.mjs --watch',
    });
    expect(pkg.devDependencies).toHaveProperty("@pob/rollup-esbuild");
    expect(plannedContent(plan, "rollup.config.mjs"))
      .toBe(`// Generated by pob: do not edit, it is overwritten on each pob run.
import configs1 from "./packages/plugin/rollup.config.mjs";
import configs2 from "./packages/lib/rollup.config.mjs";

export default [...configs1, ...configs2];
`);
  });

  test("check-only typescript: no definitions, no build", async () => {
    const plan = await runTestSteps(
      createRoot({
        pkg: { scripts: { build: "old", "build:definitions": "tsrs -b" } },
        monorepo: { typescript: "check-only" },
        workspacePackages: [
          createPackage("packages/a", {
            pkg: { name: "a" },
            config: { project: { type: "lib" }, lib: {} },
            files: { "tsconfig.json": "{}" },
          }),
        ],
      }),
      [monorepoBuildStep, monorepoTypescriptStep],
    );
    expect(plannedPkg(plan).scripts).toEqual({
      tsc: "tsrs -b",
      "tsc:go": "tsc -b",
    });
  });

  test("typescript without tsconfig in packages throws", async () => {
    await expect(
      runTestSteps(
        createRoot({
          monorepo: { typescript: true },
          workspacePackages: [
            createPackage("packages/a", {
              pkg: { name: "a" },
              config: { project: { type: "lib" }, lib: {} },
            }),
          ],
        }),
        [monorepoTypescriptStep],
      ),
    ).rejects.toThrow("no package has a tsconfig.json");
  });

  test("tools project for root scripts, excluding node apps scripts", async () => {
    const plan = await runTestSteps(
      createRoot({
        monorepo: { typescript: true },
        files: { "scripts/release.ts": "", "scripts/run.sh": "" },
        workspacePackages: [
          createPackage("packages/api", {
            pkg: { name: "api" },
            config: { project: { type: "app" }, app: { type: "node" } },
            files: { "tsconfig.json": "{}", "scripts/seed.ts": "" },
          }),
        ],
      }),
      [monorepoTypescriptStep],
    );
    expect(plannedContent(plan, "tsconfig.json")).toContain(
      '{ "path": "tsconfig.tools.json" }',
    );
    const tools = plannedContent(plan, "tsconfig.tools.json");
    expect(tools).toContain('"packages/*/scripts/**/*.ts"');
    expect(tools).toContain('"exclude": ["packages/api/scripts/**"]');
  });

  test("typescript disabled removes the typescript files and scripts", async () => {
    const plan = await runTestSteps(
      createRoot({
        pkg: {
          scripts: { tsc: "tsrs -b", "tsc:go": "tsc -b" },
          devDependencies: { tsrs: "1.0.0" },
        },
        monorepo: { typescript: false },
        files: { "tsconfig.json": "{}", "tsconfig.tools.json": "{}" },
      }),
      [monorepoTypescriptStep],
    );
    expect(plannedPkg(plan)).not.toHaveProperty("scripts");
    expect(plannedPkg(plan)).not.toHaveProperty("devDependencies");
    expect(
      plan.files
        .filter((file) => file.op === "delete")
        .map((file) => file.path),
    ).toEqual(["tsconfig.json", "tsconfig.tools.json"]);
  });

  test("app monorepo builds the workspaces in topological order", async () => {
    const plan = await runTestSteps(
      createRoot({
        project: { type: "app" },
        monorepo: { typescript: true },
        workspacePackages: [
          createPackage("packages/web", {
            pkg: {
              name: "web",
              scripts: { watch: "vite" },
              pob: { envs: [{ target: "browser" }] },
            },
            config: { project: { type: "app" }, app: { type: "vite" } },
            files: { "tsconfig.json": "{}" },
          }),
          createPackage("packages/mobile", {
            pkg: { name: "mobile" },
            config: { project: { type: "app" }, app: { type: "expo" } },
            files: { "tsconfig.json": "{}" },
          }),
        ],
      }),
      [monorepoBuildStep, monorepoTypescriptStep],
    );
    expect(plannedPkg(plan).scripts).toEqual({
      build:
        "yarn workspaces foreach --parallel --topological-dev -Av run build",
      tsc: "tsrs -b",
      "tsc:go": "tsc -b",
      watch:
        'yarn workspaces foreach --parallel --jobs unlimited --interlaced --exclude "*-example" -Av run watch',
    });
  });

  test("expo app in a lib monorepo adds upgrade-expo", async () => {
    const plan = await runTestSteps(
      createRoot({
        workspacePackages: [
          createPackage("packages/mobile", {
            pkg: { name: "mobile" },
            config: { project: { type: "app" }, app: { type: "expo" } },
          }),
        ],
      }),
      [monorepoBuildStep],
    );
    expect(plannedPkg(plan).scripts).toEqual({
      "upgrade-expo": "yarn workspaces foreach -Av run upgrade-expo",
    });
  });

  test("workspaces: npm engines, eslint disabled, readme body kept", async () => {
    const plan = await runTestSteps(
      createRoot({
        pkg: {
          name: "npm-monorepo",
          workspaces: undefined,
          lerna: {},
          scripts: { "lint:eslint": "eslint ." },
        },
        project: { packageManager: "npm" },
        monorepo: { eslint: false },
        files: {
          "README.md":
            '<h1 align="center">\n  old\n</h1>\n\n<h3>📦 Packages</h3>\n\nintro\n\n| a |\n| - |\n\n## Usage\n\nkept\n',
        },
        workspacePackages: [
          createPackage("packages/b", {
            pkg: {
              name: "b",
              description: "a & b",
              repository: { directory: "packages/b" },
            },
            config: { project: { type: "lib" }, lib: {} },
          }),
          createPackage("packages/a-example", {
            pkg: { name: "a-example", private: true },
            config: { project: { type: "app" }, app: { type: "vite" } },
          }),
          createPackage("packages/a", {
            pkg: { name: "@scope/a", private: true },
            config: { project: { type: "lib" }, lib: {} },
          }),
        ],
      }),
      [monorepoWorkspacesStep],
    );
    const pkg = plannedPkg(plan);
    expect(pkg.engines).toEqual({ npm: ">= 6.4.0", yarn: "< 0.0.0" });
    expect(pkg.workspaces).toEqual(["packages/*"]);
    expect(pkg.scripts).toEqual({
      format: "oxfmt",
      "format:check": "oxfmt --check .",
      lint: "npm run format && npm run lint:oxlint && npm run lint:eslint",
    });
    expect(plannedContent(plan, "README.md")).toBe(`<h1 align="center">
  npm
</h1>

<h3>📦 Packages</h3>

This repository is a monorepo using workspaces.

| Package              | Version                                                                                                    | Description |
| -------------------- | ---------------------------------------------------------------------------------------------------------- | ----------- |
| [@scope/a](@scope/a) |                                                                                                            |
| [b](packages/b)      | <a href="https://npmjs.org/package/b"><img src="https://img.shields.io/npm/v/b.svg?style=flat-square"></a> | a &amp; b   |

## Usage

kept
`);
  });

  test("legacy: lerna, flow and old tsconfigs", async () => {
    const plan = await runTestSteps(
      createRoot({
        pkg: {
          version: "0.0.0",
          lerna: { version: "2.0.0", npmClient: "yarn" },
          scripts: {
            version:
              "YARN_ENABLE_IMMUTABLE_INSTALLS=false yarn && git add yarn.lock",
            flow: "flow",
            postbuild: "tsc -b",
            prepublishOnly: "lerna run build",
            test: "vitest",
          },
          devDependencies: { lerna: "3.0.0", "flow-bin": "1.0.0" },
          dependencies: { "@pob/lerna-light": "3.0.0" },
        },
        files: {
          ".flowconfig": "",
          "flow-typed/x.js": "",
          "tsconfig.build.json": "{}",
          "lerna-debug.log": "",
          "docs/index.html": "",
        },
      }),
      [legacyStep],
    );
    const pkg = plannedPkg(plan);
    expect(pkg.version).toBe("2.0.0");
    expect(pkg).not.toHaveProperty("lerna");
    expect(pkg).not.toHaveProperty("dependencies");
    expect(pkg).not.toHaveProperty("devDependencies");
    expect(pkg.scripts).toEqual({ test: "vitest" });
    expect(
      plan.files
        .filter((file) => file.op === "delete")
        .map((file) => file.path)
        .toSorted(),
    ).toEqual([
      ".flowconfig",
      "docs",
      "flow-typed",
      "lerna-debug.log",
      "tsconfig.build.json",
    ]);
  });

  test("legacy: independent lerna version removes the root version", async () => {
    const plan = await runTestSteps(
      createRoot({ pkg: { version: "0.0.0" }, files: { "lerna.json": "{}" } }),
      [legacyStep],
    );
    expect(plannedPkg(plan)).not.toHaveProperty("version");
  });
});
