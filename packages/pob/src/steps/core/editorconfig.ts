import type { PackageContext } from "../../engine/context.ts";
import { defineStep } from "../../engine/step.ts";

export const editorconfigContent = `# Generated by pob: do not edit, it is overwritten on each pob run.
# EditorConfig helps developers define and maintain consistent
# coding styles between different editors and IDEs
# http://editorconfig.org

root = true

[*]
indent_style = space
indent_size = 2
end_of_line = lf
charset = utf-8
trim_trailing_whitespace = true
insert_final_newline = true
`;

export const editorconfigStep = defineStep<PackageContext>({
  name: "editorconfig",
  writes: ["files:.editorconfig"],
  run: (ctx) => {
    ctx.output.owned(".editorconfig", editorconfigContent);
  },
});
