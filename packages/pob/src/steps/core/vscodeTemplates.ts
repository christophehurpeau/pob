/**
 * The .vscode templates of pob:core:vscode, rendered to the same strings as
 * their ejs versions (formatted afterwards with oxfmt).
 */

const lines = (...parts: (string | false | undefined)[]): string =>
  parts.filter((part) => typeof part === "string").join("");

export interface ExtensionsTemplateOptions {
  yarn: boolean;
  pnp: boolean;
  typescript: boolean;
  tailwind: boolean;
}

export const renderExtensionsJson = ({
  yarn,
  pnp,
  typescript,
  tailwind,
}: ExtensionsTemplateOptions): string =>
  lines(
    `// Generated by pob: do not edit, it is overwritten on each pob run.
{
  // See http://go.microsoft.com/fwlink/?LinkId=827846 to learn about workspace recommendations.
  // Extension identifier format: \${publisher}.\${name}. Example: vscode.csharp
  // List of extensions which should be recommended for users of this workspace.
  "recommendations": [
`,
    yarn && pnp && '    "arcanis.vscode-zipfs",\n',
    `    "oxc.oxc-vscode",
    "dbaeumer.vscode-eslint",
    "EditorConfig.EditorConfig",
    "esbenp.prettier-vscode"`,
    typescript &&
      `,
    "TypeScriptTeam.native-preview"`,
    tailwind &&
      `,
    "bradlc.vscode-tailwindcss"`,
    `
  ],
  // List of extensions recommended by VS Code that should not be recommended for users of this workspace.
  "unwantedRecommendations": []
}
`,
  );

export interface SettingsTemplateOptions {
  yarn: boolean;
  pnp: boolean;
  bun: boolean;
  pnpm: boolean;
  typescript: boolean;
  tsrs: boolean;
  tailwind: boolean;
}

const renderYarnSettings = (pnp: boolean): string =>
  lines(
    pnp &&
      `  // yarn berry
  "eslint.nodePath": ".yarn/sdks",
  "prettier.prettierPath": ".yarn/sdks/prettier/index.js",
`,
    `  "search.exclude": {
    `,
    pnp &&
      `    "**/.pnp.*": true,
    `,
    `    "**/.yarn": true
  },
`,
  );

const renderTypescriptSettings = (tsrs: boolean): string =>
  lines(
    `  // typescript 7 is provided by the TypeScriptTeam.native-preview extension.
  // "typescript" resolves to the typescript 6 api package, which has no
  // tsserver, so it cannot be used as "typescript.tsdk".
`,
    tsrs &&
      `  // The extension runs tsrs, the same compiler as the "tsc" script, through
  // .vscode/tsrs-tsdk/tsgo once its "TypeScript 7 tsdk" prompt is allowed.
  // Without the prompt, use "Select TypeScript Version…", which offers the
  // "additionalLocations" entry.
  "js/ts.experimental.useTsgo": true,
  "js/ts.tsdk.path": ".vscode/tsrs-tsdk",
  "js/ts.tsdk.additionalLocations": [".vscode/tsrs-tsdk"],
  "js/ts.enablePromptUseWorkspaceTsdk": true,
`,
  );

const renderPackageManagerSettings = ({
  yarn,
  bun,
  pnpm,
}: Pick<SettingsTemplateOptions, "yarn" | "bun" | "pnpm">): string => {
  const packageManager = (() => {
    if (yarn) return "yarn";
    if (bun) return "bun";
    if (pnpm) return "pnpm";
    return undefined;
  })();
  if (!packageManager) return "";
  return `  // set ${packageManager} as package manager to run scripts and tasks
  "npm.packageManager": "${packageManager}",
`;
};

export const renderSettingsJson = (options: SettingsTemplateOptions): string =>
  lines(
    `// Generated by pob: do not edit, it is overwritten on each pob run.
{
`,
    options.yarn && renderYarnSettings(options.pnp),
    options.typescript && renderTypescriptSettings(options.tsrs),
    "\n",
    renderPackageManagerSettings(options),
    `
  // save config
  "editor.formatOnSave": true,
  "eslint.codeActionsOnSave.mode": "all",
  "editor.codeActionsOnSave": {
    "source.fixAll.oxc": "always",
    "source.fixAll.eslint": "always",
    "source.organizeImports": "never"
  },

  // extension eslint config
  "eslint.workingDirectories": ["."],
  "eslint.useFlatConfig": true,
  "eslint.lintTask.enable": true,
  "eslint.validate": [
    "javascript",
    "javascriptreact",
    "typescript",
    "typescriptreact"
  ],

  // format config
  "eslint.format.enable": false,
  "editor.defaultFormatter": "oxc.oxc-vscode",
`,
    options.tailwind &&
      `
  // tailwind config: class names in tailwind-variants tv() calls
  "tailwindCSS.classFunctions": ["tv"],
`,
    "}\n",
  );

export const renderTasksJson = (tasks: unknown[]): string => `{
  // See https://go.microsoft.com/fwlink/?LinkId=733558
  // for the documentation about the tasks.json format
  "version": "2.0.0",
  "tasks": ${JSON.stringify(tasks, null, 2)}
}
`;

export const tsrsTsdkTsgo = `#!/bin/sh
# Generated by pob: do not edit, it is overwritten on each pob run.
# "js/ts.tsdk.path" points to this directory, so that the TypeScript 7
# extension (TypeScriptTeam.native-preview) runs the project's tsrs instead of
# its bundled typescript 7. The extension silently falls back to the bundled
# one when this fails: tsrs not installed, no tsrs binary for the platform
# (Windows, Intel macOS) or node not in VS Code's PATH.
# Check with: ps -axo command | grep -- '--lsp --stdio'
exec node "$(dirname "$0")/../../node_modules/tsrs/bin/tsrs" "$@"
`;
