import type { LegacyPart } from "../legacy/part.ts";

/** from pob:common:typescript, composed by pob:lib and pob:app only */
export const typescriptLegacyPart: LegacyPart = {
  name: "typescript",
  writes: [
    "pkg.devDependencies",
    "pkg.scripts.flow",
    "files:flow-typed",
    "files:.flowconfig",
    "files:tsconfig.build.json",
    "files:tsconfig.check.json",
    "files:tsconfig.eslint.json",
  ],
  run: (ctx) => {
    if (ctx.facts.isMonorepoRoot) return;
    ctx.output.removed("flow-typed");
    ctx.output.removed(".flowconfig");
    ctx.pkg.removeDevDependencies(["flow-bin"]);
    ctx.pkg.removeScripts(["flow"]);
    ctx.output.removed("tsconfig.build.json");
    ctx.output.removed("tsconfig.check.json");
    ctx.output.removed("tsconfig.eslint.json");
  },
};

/** from pob:common:testing */
export const testingLegacyPart: LegacyPart = {
  name: "testing",
  writes: [
    "pkg.devDependencies",
    "pkg.scripts.generate:test-coverage",
    "files:babel.config.cjs",
  ],
  run: (ctx) => {
    ctx.pkg.removeDevDependencies([
      "coveralls",
      "mocha",
      "istanbul",
      "babel-core",
      "ts-jest",
      "babel-jest",
      "pob-lcov-reporter",
    ]);
    ctx.pkg.removeScripts(["generate:test-coverage"]);
    // only the jest config generated by pob: apps (expo, react-native) can
    // have their own, read by metro
    if (ctx.initial.read("babel.config.cjs")?.includes("pob-babel/preset")) {
      ctx.output.removed("babel.config.cjs");
    }
  },
};

/** from pob:core:ci */
export const ciLegacyPart: LegacyPart = {
  name: "ci",
  writes: ["files:.circleci", "files:.travis.yml", "files:circle.yml"],
  run: (ctx) => {
    // an empty directory is not a file: git does not keep it
    if (ctx.initial.listFiles(".circleci").length > 0) {
      ctx.output.removed(".circleci");
    }
    ctx.output.removed(".travis.yml");
    ctx.output.removed("circle.yml");
  },
};
