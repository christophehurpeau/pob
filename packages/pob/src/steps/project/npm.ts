import type { PackageContext } from "../../engine/context.ts";
import type { JsonObject } from "../../engine/model.ts";
import { defineStep } from "../../engine/step.ts";
import { getProjectKind } from "../settings.ts";
import { getProjectAppSettings, getProjectLibSettings } from "./settings.ts";

const npmignoreTemplate = `# Generated by pob: do not edit, it is overwritten on each pob run.
# keep an empty file to avoid using gitignore.
`;

interface NpmOptions {
  srcDirectory: string;
  distDirectory: string;
}

const getNpmOptions = (ctx: PackageContext): NpmOptions => {
  if (getProjectKind(ctx) === "lib") {
    const settings = getProjectLibSettings(ctx);
    return {
      srcDirectory: settings.srcDirectory,
      distDirectory: settings.buildDirectory,
    };
  }
  const settings = getProjectAppSettings(ctx);
  return {
    srcDirectory: settings.srcDirectory,
    distDirectory: settings.buildDirectory,
  };
};

/** the sources and the type definitions of the built tests */
const testFilesExclusion = "!**/*.test.*";

const computeFiles = (
  ctx: PackageContext,
  options: NpmOptions,
  currentFiles: string[] | undefined,
): string[] => {
  const { pkg } = ctx;
  const files = new Set([options.srcDirectory, options.distDirectory]);
  if (pkg.get("bin")) files.add("bin");
  if (ctx.initial.exists("skills")) files.add("skills");

  const exports = pkg.get<JsonObject | string>("exports");
  if (exports && typeof exports === "object") {
    for (const value of Object.values(exports)) {
      if (typeof value !== "string") continue;
      if (value.startsWith("./tsconfigs/")) files.add("tsconfigs");
      if (
        value.startsWith("./") &&
        value !== "./package.json" &&
        ![...files].some((file) => value.startsWith(`./${file}/`))
      ) {
        files.add(value.slice("./".length));
      }
    }
  }
  for (const extraEntry of (ctx.config.build?.extraEntries ?? []) as {
    directory?: string;
  }[]) {
    if (extraEntry.directory) files.add(extraEntry.directory);
  }

  const exclusions = (currentFiles ?? []).filter((file) =>
    file.startsWith("!"),
  );
  return [...files, ...new Set([testFilesExclusion, ...exclusions])].filter(
    Boolean,
  );
};

/** pob:core:npm: published files of libs and apps */
export const npmStep = defineStep<PackageContext>({
  name: "npm",
  when: (ctx) => getProjectKind(ctx) !== "monorepo",
  reads: ["pkg.private", "pkg.bin", "pkg.exports"],
  writes: ["pkg.files", "files:.npmignore"],
  run(ctx) {
    const { pkg, output } = ctx;
    if (pkg.get("private")) {
      output.removed(".npmignore");
      pkg.delete("files");
      return;
    }
    output.owned(".npmignore", npmignoreTemplate);
    const currentFiles = pkg.get<string[]>("files");
    // a single built entry, see rollup-plugin-svgr
    if (currentFiles?.length === 1 && currentFiles[0] === "lib/index.js") {
      return;
    }
    pkg.set("files", computeFiles(ctx, getNpmOptions(ctx), currentFiles));
  },
});
