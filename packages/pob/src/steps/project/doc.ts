import JSON5 from "json5";
import type { PackageContext } from "../../engine/context.ts";
import type { JsonObject } from "../../engine/model.ts";
import { defineStep } from "../../engine/step.ts";
import { finalFileContent } from "../monorepo/packages.ts";
import { getProjectKind, hasReact } from "../settings.ts";
import { escapeHtml as e } from "./escape.ts";
import { getProjectLibSettings } from "./settings.ts";

const testExtension = (jsx: boolean): string => (jsx ? "x?" : "");

const renderEntryPoints = (entryPoints: string[]): string =>
  entryPoints.map((entryPoint) => `"${entryPoint}"`).join(", ");

interface LibTsconfigDocOptions {
  jsx: boolean;
  readme: string;
  entryPoints: string[];
}

/** templates/tsconfig.doc.json.ejs of pob:lib:doc */
export const renderLibTsconfigDoc = ({
  jsx,
  readme,
  entryPoints,
}: LibTsconfigDocOptions): string => `// Generated by pob: do not edit, it is overwritten on each pob run.
{
  "extends": "./tsconfig.json",

  "typedocOptions": {
    "entryPoints": [
      ${renderEntryPoints(entryPoints)}
    ],
    "exclude": [
      "src/**/*.test.ts${testExtension(jsx)}",
      "src/**/__tests__/**"
    ],
    "readme": "${e(readme)}",
    "out": "generated-docs",
    "excludePrivate": true,
    "gitRevision": "main"
  },

  "exclude": [
    "src/**/*.test.ts${testExtension(jsx)}",
    "src/**/__tests__/**"
  ]
}
`;

interface MonorepoTsconfigDocOptions extends LibTsconfigDocOptions {
  packagePaths: string[];
}

/** templates/tsconfig.doc.json.lerna.ejs of pob:lib:doc */
export const renderMonorepoTsconfigDoc = ({
  jsx,
  readme,
  entryPoints,
  packagePaths,
}: MonorepoTsconfigDocOptions): string => {
  const references = packagePaths
    .map(
      (packagePath, index) =>
        `    { "path": "${e(packagePath)}/tsconfig.json" }${index === packagePaths.length - 1 ? "" : ","}\n`,
    )
    .join("");
  return `// Generated by pob: do not edit, it is overwritten on each pob run.
{
  "files": [],

  "exclude": [
    "**/node_modules/**",
    "**/src/**/*.test.ts${testExtension(jsx)}",
    "**/src/**/__tests__/**"
  ],

  "compilerOptions": {
    "target": "esnext",
    "module": "esnext",
    "lib": ["dom", "esnext"],
    "skipLibCheck": true,
    "moduleResolution": "bundler",
    "esModuleInterop": true
  },

  "references": [
${references}  ],

  "typedocOptions": {
    "entryPoints": [
      ${renderEntryPoints(entryPoints)}
    ],
    "exclude": [
      "**/*.test.ts${testExtension(jsx)}",
      "**/__tests__/**"
    ],
    "readme": "${e(readme)}",
    "out": "generated-docs",
    "excludePrivate": true,
    "gitRevision": "master"
  }
}
`;
};

const getJsx = (ctx: PackageContext): boolean => {
  const jsx = ctx.config.build?.jsx;
  if (jsx !== undefined) return jsx;
  return hasReact({
    dependencies: ctx.pkg.get("dependencies"),
    peerDependencies: ctx.pkg.get("peerDependencies"),
  });
};

/**
 * The packages with a pob config, in topological order, only those with a
 * tsconfig.json once their steps ran in a typescript monorepo: the same state
 * the root tsconfig.json references.
 */
const renderMonorepoDoc = (ctx: PackageContext, jsx: boolean): string => {
  const typescript = !!ctx.config.monorepo?.typescript;
  const packages = ctx.workspacePackages.filter(
    (workspacePackage) =>
      (!typescript ||
        finalFileContent(workspacePackage, "tsconfig.json") !== undefined) &&
      !workspacePackage.location.endsWith("-example"),
  );
  const entryPoints: string[] = [];
  for (const workspacePackage of packages) {
    const entries = workspacePackage.config.build?.entries;
    if (entries) {
      // https://typedoc.org/guides/project-references/
      entryPoints.unshift(
        ...entries.map(
          (entry) => `${workspacePackage.location}/src/${entry}.ts`,
        ),
      );
    }
  }
  const existingConfig = ((): JsonObject => {
    const content = ctx.initial.read("tsconfig.doc.json");
    return content === undefined
      ? {}
      : (JSON5.parse<JsonObject>(content) ?? {});
  })();
  const typedocOptions = existingConfig.typedocOptions as
    | { readme?: string }
    | undefined;
  return renderMonorepoTsconfigDoc({
    jsx,
    readme: typedocOptions?.readme || "README.md",
    entryPoints,
    packagePaths: packages.map(({ location }) => location),
  });
};

/** pob:lib:doc, for libs and monorepo roots */
export const docStep = defineStep<PackageContext>({
  name: "doc",
  when: (ctx) => getProjectKind(ctx) !== "app",
  reads: ["pkg.dependencies", "pkg.peerDependencies"],
  writes: [
    "pkg.devDependencies",
    "pkg.scripts.generate:api",
    "files:tsconfig.doc.json",
  ],
  run(ctx) {
    const { pkg, output } = ctx;
    const isMonorepoRoot = ctx.facts.isMonorepoRoot;
    const enabled = isMonorepoRoot
      ? !!ctx.config.monorepo?.documentation
      : getProjectLibSettings(ctx).documentation;

    if (enabled) {
      const jsx = getJsx(ctx);
      const content = isMonorepoRoot
        ? renderMonorepoDoc(ctx, jsx)
        : renderLibTsconfigDoc({
            jsx,
            readme: "README.md",
            entryPoints: (ctx.config.build?.entries ?? []).map(
              (entryName) => `src/${entryName}.ts`,
            ),
          });
      output.owned("tsconfig.doc.json", content, { format: "oxfmt" });
    } else {
      output.removed("tsconfig.doc.json");
    }

    pkg.addOrRemoveDevDependencies(enabled, ["typedoc"]);
    pkg.addOrRemoveScripts(enabled, {
      "generate:api": "typedoc --tsconfig tsconfig.doc.json",
    });
  },
});
